export const translateDescription = (desc: string, type: string, lang: string) => {
  if (!lang.toLowerCase().startsWith('pt')) return desc;
  
  if (type === 'iconify') {
    const iconName = desc.includes(':') ? desc.split(':')[1] : desc;
    for (const [term, icons] of Object.entries(iconTranslationsPTBR)) {
      if (icons.includes(iconName)) return term;
    }
    for (const [term, icons] of Object.entries(iconTranslationsPTBR)) {
      if (icons.some(i => iconName.includes(i) || i.includes(iconName))) return term;
    }
  }

  if (type === 'pexels' || type === 'image') {
    // Remove pontuação uma única vez e converte para minúsculas
    const cleanDesc = desc.toLowerCase().replace(/[.,\/#!$%\^&\*;:{}=\-_`~()]/g, "");
    const words = cleanDesc.split(/\s+/);
    const translatedWords = words.map(word => commonTranslations[word] || word);
    return translatedWords.join(' ');
  }
  
  return desc;
};
